// Generates the README beside every component, the folder READMEs, and the component index in the
// top-level README. The source of truth is each component's `*.demo.tsx` file (title, summary, usage,
// props) and the doc comments on exported functions and types.
//
//   node scripts/docs.mjs           write the files
//   node scripts/docs.mjs --check   exit 1 if any file is out of date (used in CI)

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const DEMO_SITE = 'https://gurfi1.github.io/react-shopify-style-checkout/';
const CHECK = process.argv.includes('--check');
const NOTE = '<!-- Generated by scripts/docs.mjs from the demo file and doc comments. Edit those, then run `npm run docs`. -->';

const read = path => readFileSync(path, 'utf8');
const slug = title => title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const cell = text => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
// Angle brackets outside `code` would be read as HTML by Markdown.
const prose = text => String(text).split('`').map((part, position) => (position % 2 ? part : part.replace(/</g, '&lt;'))).join('`');
const firstSentence = text => (text.match(/^.*?[.!?](?=\s|$)/s)?.[0] ?? text).trim();
const folders = parent => readdirSync(join(SRC, parent)).filter(name => statSync(join(SRC, parent, name)).isDirectory()).sort();
const sourceFiles = dir => readdirSync(dir).filter(name => /\.(tsx?|css)$/.test(name) && !/\.(demo|test)\./.test(name)).sort();

// ---- Demo files: the metadata is a plain object literal up to its `Example` property. ----
function readDemo(path) {
  const text = read(path);
  const start = text.indexOf('const demo: Demo = {');
  const end = text.indexOf('\n  Example:', start);
  if (start < 0 || end < 0) throw new Error(`Cannot find the demo metadata in ${relative(ROOT, path)}`);
  const literal = text.slice(start + 'const demo: Demo = '.length, end) + '\n}';
  return Function(`"use strict"; return (${literal});`)();
}

// ---- Doc comments: `/** … */` directly above an exported function, const or type. ----
function readExports(path) {
  const found = [];
  const pattern = /\/\*\*((?:(?!\*\/)[\s\S])*?)\*\/\s*export (?:async )?(function|const|type) (\w+)/g;
  for (const match of read(path).matchAll(pattern)) {
    const description = match[1].split('\n').map(line => line.replace(/^\s*\*? ?/, '')).join(' ').replace(/\s+/g, ' ').trim();
    found.push({ kind: match[2], name: match[3], description });
  }
  return found;
}

// ---- Dependencies: what else has to be copied for a folder to work on its own. ----
function importsOf(path) {
  const from = [];
  for (const match of read(path).matchAll(/(?:import|export)[^'";]*?from\s+'(\.[^']+)'|import\s+'(\.[^']+)'/g)) {
    const target = resolve(dirname(path), match[1] ?? match[2]);
    const file = [target, target + '.tsx', target + '.ts', join(target, 'index.tsx'), join(target, 'index.ts')].find(candidate => existsSync(candidate) && statSync(candidate).isFile());
    if (file) from.push(file);
  }
  return from;
}

/** The unit a source file belongs to: a component folder, or a single shared file. */
function unitOf(file) {
  const parts = relative(SRC, file).split('/');
  if ((parts[0] === 'primitives' || parts[0] === 'checkout') && parts.length > 2) return `src/${parts[0]}/${parts[1]}`;
  if (['theme', 'icons', 'hooks', 'lib'].includes(parts[0])) return parts[0] === 'hooks' || parts[0] === 'lib' ? `src/${parts.join('/')}` : `src/${parts[0]}`;
  return `src/${parts.join('/')}`;
}

function dependenciesOf(dir) {
  const own = `src/${relative(SRC, dir)}`;
  const seen = new Set();
  const queue = sourceFiles(dir).filter(name => !name.endsWith('.css')).map(name => join(dir, name));
  const units = new Set();
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    for (const next of importsOf(file)) {
      if (/\.(css|svg)$/.test(next)) continue;
      const unit = unitOf(next);
      if (unit !== own) units.add(unit);
      queue.push(next);
    }
  }
  return [...units].sort();
}

// ---- Pages ----
const outputs = new Map();
const index = { Components: [], 'Checkout blocks': [] };

function componentPage(parent, name) {
  const dir = join(SRC, parent, name);
  const here = `src/${parent}/${name}`;
  const demos = readdirSync(dir).filter(file => file.endsWith('.demo.tsx')).sort((a, b) => (a.startsWith(name) ? -1 : b.startsWith(name) ? 1 : a.localeCompare(b))).map(file => readDemo(join(dir, file)));
  const lines = [NOTE, ''];

  if (demos.length) {
    demos.forEach((demo, position) => {
      const section = demo.group === 'Components' ? 'components' : 'blocks';
      lines.push(`${position === 0 ? '#' : '##'} ${demo.title}`, '', prose(demo.summary), '', `[Live demo](${DEMO_SITE}#/${section}/${slug(demo.title)})`, '');
      const deeper = position === 0 ? '##' : '###';
      lines.push(`${deeper} Usage`, '', '```tsx', demo.usage, '```', '');
      if (demo.props?.length) {
        lines.push(`${deeper} Props`, '', '| Prop | Type | What it does |', '|---|---|---|');
        for (const [prop, type, description] of demo.props) lines.push(`| \`${cell(prop)}\` | ${type ? '`' + cell(type) + '`' : ''} | ${cell(prose(description))} |`);
        lines.push('');
      }
      index[demo.group].push({ order: demo.order, title: demo.title, summary: prose(firstSentence(demo.summary)), path: here });
    });
  } else {
    const exported = sourceFiles(dir).filter(file => !file.endsWith('.css')).flatMap(file => readExports(join(dir, file))).filter(item => item.kind !== 'type');
    lines.push(`# ${name}`, '', ...exported.flatMap(item => [`**\`${item.name}\`** ${prose(item.description)}`, '']));
  }

  const files = sourceFiles(dir);
  const needs = dependenciesOf(dir);
  lines.push('## Files', '', 'To use this on its own, copy this folder:', '', ...files.map(file => `- \`${file}\``), '');
  if (existsSync(join(dir, 'brands'))) lines.push('- `brands/` (the card logos and their licence)', '');
  if (needs.length) lines.push('It also needs:', '', ...needs.map(unit => `- [\`${unit}\`](${relative(dir, join(ROOT, unit)) || '.'})`), '');
  else lines.push('It needs nothing else.', '');
  lines.push('Everything expects a [`Theme`](' + relative(dir, join(SRC, 'theme')) + ') somewhere above it, which supplies the colours, corners and timings.', '');
  outputs.set(join(dir, 'README.md'), lines.join('\n'));
}

function listingPage(dir, title, intro, files) {
  const lines = [NOTE, '', `# ${title}`, '', intro, ''];
  for (const file of files) {
    const exported = readExports(join(dir, file));
    if (!exported.length) continue;
    lines.push(`## \`${file}\``, '', '| Name | What it is |', '|---|---|');
    for (const item of exported) lines.push(`| \`${item.name}\` | ${cell(prose(item.description))} |`);
    lines.push('');
  }
  outputs.set(join(dir, 'README.md'), lines.join('\n'));
}

function folderIndexPage(parent, title, intro, group) {
  const rows = index[group].slice().sort((a, b) => a.order - b.order);
  const lines = [NOTE, '', `# ${title}`, '', intro, '', '| Component | What it is |', '|---|---|'];
  for (const row of rows) lines.push(`| [${row.title}](${relative(join(SRC, parent), join(ROOT, row.path))}) | ${cell(row.summary)} |`);
  const undocumented = folders(parent).filter(name => !rows.some(row => row.path.endsWith('/' + name)));
  for (const name of undocumented) lines.push(`| [${name}](${name}) | Shared by other components; see its README. |`);
  lines.push('');
  outputs.set(join(SRC, parent, 'README.md'), lines.join('\n'));
}

for (const name of folders('primitives')) componentPage('primitives', name);
for (const name of folders('checkout')) componentPage('checkout', name);

folderIndexPage('primitives', 'Building blocks', 'Components that work anywhere. Each folder holds one component with its own stylesheet, a demo file and a README, and needs only a `Theme` above it.', 'Components');
folderIndexPage('checkout', 'Checkout blocks', 'Larger pieces of a checkout, each usable without the rest. They take their data as props and read wording and currency from `CheckoutProvider` (in `CheckoutProvider.tsx` in this folder), falling back to English and US dollars.', 'Checkout blocks');

listingPage(join(SRC, 'hooks'), 'Hooks', 'The checkout\'s behaviour with no interface attached. `useCheckout` is the whole page\'s state and rules; the others are the smaller pieces it and the components are built from.', readdirSync(join(SRC, 'hooks')).filter(file => file.endsWith('.ts')).sort());
listingPage(join(SRC, 'lib'), 'Logic', 'Plain functions with no React in them: formatting, validation, address formats, totals. They are covered by the tests in `lib.test.ts`.', readdirSync(join(SRC, 'lib')).filter(file => file.endsWith('.ts') && !file.endsWith('.test.ts')).sort());
listingPage(join(SRC, 'locales'), 'Locales', 'Complete sets of wording in other languages. Each one is typed as `Labels`, so the compiler reports a label that is missing. Pass one as `labels`; [docs/wording-and-locale.md](../../docs/wording-and-locale.md) explains how, and how to add a language.', readdirSync(join(SRC, 'locales')).filter(file => file.endsWith('.ts') && !file.endsWith('.test.ts')).sort());
listingPage(join(SRC, 'icons'), 'Icons', 'The icon set, drawn for this project as stroked paths. Each icon takes the current text colour and a `size` in pixels.', ['index.tsx']);
listingPage(join(SRC, 'theme'), 'Theme', 'Design tokens and base type. Every other component expects a `Theme` above it. The tokens themselves are in `Theme.module.css`; [docs/theming.md](../../docs/theming.md) lists them.', ['Theme.tsx']);

// ---- The component index in the top-level README ----
const readmePath = join(ROOT, 'README.md');
if (existsSync(readmePath)) {
  const table = group => ['| Component | What it is |', '|---|---|', ...index[group].slice().sort((a, b) => a.order - b.order).map(row => `| [${row.title}](${row.path}) | ${cell(row.summary)} |`)].join('\n');
  const block = `<!-- components:start -->\n### Building blocks\n\n${table('Components')}\n\n### Checkout blocks\n\n${table('Checkout blocks')}\n<!-- components:end -->`;
  const current = read(readmePath);
  if (/<!-- components:start -->[\s\S]*<!-- components:end -->/.test(current)) outputs.set(readmePath, current.replace(/<!-- components:start -->[\s\S]*<!-- components:end -->/, () => block));
  else console.warn('README.md has no components:start / components:end markers; the index was not written.');
}

// ---- Write or check ----
const stale = [];
for (const [path, content] of outputs) {
  const text = content.endsWith('\n') ? content : content + '\n';
  const current = existsSync(path) ? read(path) : null;
  if (current === text) continue;
  stale.push(relative(ROOT, path));
  if (!CHECK) writeFileSync(path, text);
}
if (CHECK && stale.length) {
  console.error(`${stale.length} generated file(s) are out of date. Run \`npm run docs\`.\n` + stale.map(path => '  ' + path).join('\n'));
  process.exit(1);
}
console.log(CHECK ? `All ${outputs.size} generated files are up to date.` : `${outputs.size} files generated, ${stale.length} changed.`);
